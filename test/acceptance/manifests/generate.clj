;; Acceptance entrypoint generator: bb test/acceptance/manifests/generate.clj <json-ir> <generated-dir>
;;
;; Writes <generated-dir>/<name>_test.clj, a thin entry point that runs every
;; scenario of the IR through the runtime and step handlers, and
;; <generated-dir>/metadata/<name>.json. The feature path is the IR path below
;; its "ir/" directory with .feature for .json: run.sh writes the IR of
;; test/features/x.feature to tmp/acceptance/manifests/ir/test/features/x.json.
(require '[babashka.fs :as fs]
         '[cheshire.core :as json]
         '[clojure.string :as str])
(import '[java.security MessageDigest])

(defn- feature-path [ir-path]
  (let [path (str/replace (str ir-path) #"\\" "/")
        below (second (re-find #"(?:^|/)ir/(.+)\.json$" path))]
    (str (or below (str/replace (fs/file-name path) #"\.json$" "")) ".feature")))

(defn- metadata-name [feature]
  (-> (str/lower-case feature) (str/replace #"[^a-z0-9]+" "-") (str/replace #"^-|-$" "")))

(defn- sha256 [text]
  (let [digest (.digest (MessageDigest/getInstance "SHA-256") (.getBytes text "UTF-8"))]
    (apply str (map #(format "%02x" (bit-and % 0xff)) digest))))

(defn- entry-point [ir-path ir]
  (str ";; Generated by test/acceptance/manifests/generate.clj. Do not edit.\n"
       ";; Usage: bb -cp test <this file> [json-ir]; the default IR is the one it was made from.\n"
       "(require '[acceptance.manifests.runtime :as runtime]\n"
       "         '[acceptance.manifests.steps :as steps])\n\n"
       "(def ir-path (or (first *command-line-args*) " (pr-str (str ir-path)) "))\n\n"
       "(def scenarios\n  ["
       (str/join "\n   " (map-indexed (fn [i {:strs [name]}] (str i " ; " name)) (get ir "scenarios")))
       "\n  ])\n\n"
       "(System/exit (if (zero? (runtime/run-scenarios steps/suite ir-path scenarios)) 0 1))\n"))

(defn- generate [ir-path out-dir]
  (let [ir (json/parse-string (slurp ir-path))
        feature (feature-path ir-path)
        name (metadata-name feature)
        test-file (str (fs/path out-dir (str name "_test.clj")))
        code (entry-point ir-path ir)]
    (fs/create-dirs (fs/path out-dir "metadata"))
    (spit test-file code)
    (spit (str (fs/path out-dir "metadata" (str name ".json")))
          (json/generate-string (array-map "schema_version" 1
                                           "feature_path" feature
                                           "ir_path" (str ir-path)
                                           "implementation_hash" (str "sha256:" (sha256 code))
                                           "hash_scope" "generated_files"
                                           "generated_files" [test-file])
                                {:pretty true}))))

(let [args *command-line-args*]
  (if (not= 2 (count args))
    (do (binding [*out* *err*] (println "usage: generate.clj <json-ir> <generated-dir>"))
        (System/exit 2))
    (try (apply generate args)
         (catch Exception e
           (binding [*out* *err*] (println (str "generate.clj: " (ex-message e))))
           (System/exit 1)))))
