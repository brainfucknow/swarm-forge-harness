(ns acceptance.generate
  "acceptance-entrypoint-generator: writes a thin bb entry point for the feature
  in an APS JSON IR file, and its metadata. Usage: generate <json-ir> <out-dir>.
  ACCEPTANCE_FEATURE names the feature file for the metadata."
  (:require [babashka.fs :as fs]
            [cheshire.core :as json]
            [clojure.string :as str])
  (:import (java.security MessageDigest)))

(defn- stem [ir-path]
  (str/replace (fs/file-name ir-path) #"\.json$" ""))

(defn steps-namespace
  "The step handlers for the feature at feature-path: acceptance.store-steps
  for test/features/task_store, acceptance.metrics-steps for
  test/features/metrics_cache, else acceptance.steps."
  [feature-path]
  (condp #(str/includes? %2 %1) (str feature-path)
    "task_store/" 'acceptance.store-steps
    "metrics_cache/" 'acceptance.metrics-steps
    'acceptance.steps))

(defn entry-point [ir-path feature-name feature-path]
  (str ";; Generated by test/acceptance/src/acceptance/generate.clj. Do not edit.\n"
       ";; Runs every scenario execution of the feature " (pr-str feature-name) ".\n"
       ";; ACCEPTANCE_IR names another IR file to run in place of the generated one.\n"
       "(require '[acceptance.runtime :as runtime] '[" (steps-namespace feature-path) " :as steps])\n"
       "(runtime/main (or (System/getenv \"ACCEPTANCE_IR\") " (pr-str (str ir-path)) ")\n"
       "              steps/handlers steps/new-world)\n"))

(defn metadata-name [feature-path]
  (str (-> (str/lower-case feature-path)
           (str/replace #"[^a-z0-9]+" "-")
           (str/replace #"^-|-$" ""))
       ".json"))

(defn- sha256 [text]
  (let [digest (.digest (MessageDigest/getInstance "SHA-256") (.getBytes text "UTF-8"))]
    (apply str (map #(format "%02x" (bit-and % 0xff)) digest))))

(defn generate [ir-path out-dir feature-path]
  (let [ir (json/parse-string (slurp (str ir-path)))
        file (str (fs/path out-dir (str (stem ir-path) "_acceptance.clj")))
        text (entry-point ir-path (get ir "name") feature-path)]
    (fs/create-dirs (fs/path out-dir "metadata"))
    (spit file text)
    (spit (str (fs/path out-dir "metadata" (metadata-name feature-path)))
          (json/generate-string {:schema_version 1
                                 :feature_path feature-path
                                 :ir_path (str ir-path)
                                 :implementation_hash (str "sha256:" (sha256 text))
                                 :hash_scope "generated_files"
                                 :generated_files [file]}
                                {:pretty true}))))

(defn -main [& args]
  (if (not= 2 (count args))
    (do (binding [*out* *err*] (println "usage: generate <json-ir> <generated-test-output>"))
        (System/exit 2))
    (let [[ir-path out-dir] args]
      (try
        (generate ir-path out-dir (or (System/getenv "ACCEPTANCE_FEATURE") (str (stem ir-path) ".feature")))
        (System/exit 0)
        (catch Exception e
          (binding [*out* *err*] (println (str "generate: " (ex-message e))))
          (System/exit 1))))))
